// Astro file output emits dist/**/*.html. Netlify pretty URLs also serve those
// files at the extensionless path, so /platform/rcm.html returns 200 unless a
// forced redirect wins. Splats only match at the end of a path, so "/*.html"
// never catches nested files. Write one forced 301 per HTML file instead.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const dist = path.resolve('dist');

async function walk(dir) {
  const out = [];
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...await walk(full));
    else if (entry.name.endsWith('.html')) out.push(full);
  }
  return out;
}

function destination(rel) {
  let next = rel.replace(/\.html$/i, '');
  next = next.replace(/\/index$/i, '');
  if (next === '') next = '/';
  return next;
}

const files = await walk(dist);
const lines = [
  '# Generated by scripts/html-redirects.mjs. Forced so the static .html file does not win.',
];
for (const file of files.sort()) {
  const rel = `/${path.relative(dist, file).split(path.sep).join('/')}`;
  if (rel === '/404.html') continue;
  const dest = destination(rel);
  if (dest === rel) continue;
  lines.push(`${rel}  ${dest}  301!`);
}

const redirectsPath = path.join(dist, '_redirects');
let existing = '';
try {
  existing = await readFile(redirectsPath, 'utf8');
} catch {
  existing = '';
}
const body = `${existing.trim()}${existing.trim() ? '\n' : ''}${lines.join('\n')}\n`;
await writeFile(redirectsPath, body);

const required = '/platform/rcm.html  /platform/rcm  301!';
if (!body.includes(required)) {
  console.error('html-redirects: missing', required);
  process.exit(1);
}
console.log(`html-redirects: wrote ${lines.length - 1} forced 301s`);
